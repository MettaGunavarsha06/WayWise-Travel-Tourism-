/**
 * Returns translated destination metadata (name, subtitle, state, category) based on selected language
 */
export const getTranslatedDestination = (destination, langCode = 'en') => {
  if (!destination) return destination;
  if (!langCode || langCode === 'en') return destination;

  const destTrans = DESTINATION_TRANSLATIONS[destination.id]?.[langCode];
  if (!destTrans) return destination;

  return {
    ...destination,
    name: destTrans.name || destination.name,
    subtitle: destTrans.subtitle || destination.subtitle,
    state: destTrans.state || destination.state,
    category: destTrans.category || destination.category,
  };
};
